/**
 * Mounts interactive behaviors onto a SlitTypeFaq element.
 */
export function mountSlitTypeFaq(hostElement, options = {}) {
  const root = typeof hostElement === 'string' ? document.querySelector(hostElement) : hostElement;
  if (!root) return () => {};

  const stfSection = root.matches('.stf') ? root : root.querySelector('.stf');
  if (!stfSection) return () => {};

  const isAr = stfSection.getAttribute('dir') === 'rtl';
  let activeCategory = 'all';
  let searchQuery = '';
  let activeOpenId = null;

  // Find first open item
  const initialOpenItem = stfSection.querySelector('.stf-item[data-state="open"]');
  if (initialOpenItem) {
    activeOpenId = initialOpenItem.getAttribute('data-id');
  }

  // --- Intro Slit Animation via IntersectionObserver ---
  let introObserver = null;
  if (typeof IntersectionObserver !== 'undefined') {
    introObserver = new IntersectionObserver((entries) => {
      if (entries.some(e => e.isIntersecting)) {
        stfSection.setAttribute('data-intro', 'done');
        introObserver.disconnect();
      }
    }, { threshold: 0.15 });
    introObserver.observe(stfSection);
  } else {
    stfSection.setAttribute('data-intro', 'done');
  }

  // Safety fallback
  const introTimeout = setTimeout(() => {
    stfSection.setAttribute('data-intro', 'done');
  }, 2000);

  // --- Ticker Play/Pause ---
  const tickerContainer = stfSection.querySelector('.stf-ticker');
  const tickerToggle = stfSection.querySelector('.stf-ticker-toggle');
  const pauseIcon = tickerToggle?.querySelector('.stf-ticker-pause-icon');
  const playIcon = tickerToggle?.querySelector('.stf-ticker-play-icon');

  function handleTickerToggle() {
    if (!tickerContainer) return;
    const isPaused = tickerContainer.getAttribute('data-paused') === 'true';
    tickerContainer.setAttribute('data-paused', isPaused ? 'false' : 'true');
    tickerToggle?.setAttribute('aria-pressed', isPaused ? 'false' : 'true');
    if (pauseIcon) pauseIcon.style.display = isPaused ? 'block' : 'none';
    if (playIcon) playIcon.style.display = isPaused ? 'none' : 'block';
  }
  tickerToggle?.addEventListener('click', handleTickerToggle);

  // --- Category Chips & Counts ---
  const items = Array.from(stfSection.querySelectorAll('.stf-item'));
  const chips = Array.from(stfSection.querySelectorAll('.stf-chip'));
  const countDisplay = stfSection.querySelector('.stf-count');
  const emptyContainer = stfSection.querySelector('.stf-empty');
  const searchInput = stfSection.querySelector('#stf-search-input');
  const clearBtn = stfSection.querySelector('.stf-clear');
  const resetBtn = stfSection.querySelector('.stf-reset');

  function updateCountsAndVisibility() {
    const query = searchQuery.trim().toLowerCase();
    const queryWords = getQueryWords(query);
    let visibleCount = 0;
    const catCounts = { all: 0 };

    items.forEach(item => {
      const qText = item.querySelector('.stf-q')?.textContent || '';
      const aText = item.querySelector('.stf-text')?.textContent || '';
      const combined = `${qText} ${aText}`.toLowerCase();
      const itemCat = item.getAttribute('data-category');

      // Check text match
      const matchesSearch = !queryWords.length || queryWords.every(w => combined.includes(w));

      if (matchesSearch) {
        catCounts.all = (catCounts.all || 0) + 1;
        catCounts[itemCat] = (catCounts[itemCat] || 0) + 1;
      }

      // Check category match
      const matchesCategory = activeCategory === 'all' || itemCat === activeCategory;
      const isVisible = matchesSearch && matchesCategory;

      item.style.display = isVisible ? '' : 'none';
      if (isVisible) visibleCount++;

      // Apply highlights
      const qEl = item.querySelectorAll('.stf-q');
      const aEl = item.querySelector('.stf-text p');
      if (queryWords.length) {
        qEl.forEach(el => { el.innerHTML = highlightText(qText, query); });
        if (aEl) aEl.innerHTML = highlightText(aText, query);
      } else {
        qEl.forEach(el => { el.textContent = qText; });
        if (aEl) aEl.textContent = aText;
      }
    });

    // Update active state on chips
    chips.forEach(chip => {
      const catId = chip.getAttribute('data-category');
      chip.setAttribute('aria-pressed', catId === activeCategory ? 'true' : 'false');
    });

    // Toggle empty state
    if (emptyContainer) {
      emptyContainer.style.display = visibleCount === 0 ? 'block' : 'none';
    }

    if (clearBtn) {
      clearBtn.style.display = query ? 'flex' : 'none';
    }
  }

  // Chip click handlers
  chips.forEach(chip => {
    chip.addEventListener('click', () => {
      activeCategory = chip.getAttribute('data-category') || 'all';
      updateCountsAndVisibility();
    });
  });

  // Search input handlers
  function onSearchInput(e) {
    searchQuery = e.target.value;
    updateCountsAndVisibility();
  }
  searchInput?.addEventListener('input', onSearchInput);

  function clearSearch() {
    if (searchInput) {
      searchInput.value = '';
      searchQuery = '';
      searchInput.focus();
    }
    updateCountsAndVisibility();
  }
  clearBtn?.addEventListener('click', clearSearch);

  function resetFilters() {
    searchQuery = '';
    activeCategory = 'all';
    if (searchInput) searchInput.value = '';
    updateCountsAndVisibility();
  }
  resetBtn?.addEventListener('click', resetFilters);

  // --- Accordion Open/Close with Ink Flood Animation ---
  const closingTimers = new Map();

  function toggleItem(targetId) {
    const item = items.find(it => it.getAttribute('data-id') === targetId);
    if (!item) return;

    const isOpen = item.getAttribute('data-state') === 'open';
    const btn = item.querySelector('.stf-btn');

    if (isOpen) {
      // Close this item with wipe-out animation
      item.setAttribute('data-state', 'closing');
      btn?.setAttribute('aria-expanded', 'false');
      activeOpenId = null;

      clearTimeout(closingTimers.get(targetId));
      const timer = setTimeout(() => {
        item.setAttribute('data-state', 'closed');
        closingTimers.delete(targetId);
      }, 280);
      closingTimers.set(targetId, timer);
    } else {
      // In single mode: close currently open item first
      if (activeOpenId && activeOpenId !== targetId) {
        const prevItem = items.find(it => it.getAttribute('data-id') === activeOpenId);
        if (prevItem) {
          const prevBtn = prevItem.querySelector('.stf-btn');
          prevItem.setAttribute('data-state', 'closing');
          prevBtn?.setAttribute('aria-expanded', 'false');

          clearTimeout(closingTimers.get(activeOpenId));
          const pTimer = setTimeout(() => {
            prevItem.setAttribute('data-state', 'closed');
            closingTimers.delete(activeOpenId);
          }, 280);
          closingTimers.set(activeOpenId, pTimer);
        }
      }

      // Open new item
      clearTimeout(closingTimers.get(targetId));
      item.setAttribute('data-state', 'open');
      btn?.setAttribute('aria-expanded', 'true');
      activeOpenId = targetId;
    }
  }

  // Attach button click & keydown handlers
  items.forEach((item, index) => {
    const btn = item.querySelector('.stf-btn');
    const itemId = item.getAttribute('data-id');

    btn?.addEventListener('click', (e) => {
      e.preventDefault();
      toggleItem(itemId);
    });

    btn?.addEventListener('keydown', (e) => {
      const visibleButtons = items
        .filter(it => it.style.display !== 'none')
        .map(it => it.querySelector('.stf-btn'))
        .filter(Boolean);

      const curIdx = visibleButtons.indexOf(btn);
      if (curIdx < 0) return;

      if (e.key === 'ArrowDown') {
        e.preventDefault();
        const next = (curIdx + 1) % visibleButtons.length;
        visibleButtons[next]?.focus();
      } else if (e.key === 'ArrowUp') {
        e.preventDefault();
        const prev = (curIdx - 1 + visibleButtons.length) % visibleButtons.length;
        visibleButtons[prev]?.focus();
      } else if (e.key === 'Home') {
        e.preventDefault();
        visibleButtons[0]?.focus();
      } else if (e.key === 'End') {
        e.preventDefault();
        visibleButtons[visibleButtons.length - 1]?.focus();
      }
    });

    // Copy link button handler
    const copyBtn = item.querySelector('.stf-copy');
    copyBtn?.addEventListener('click', async (e) => {
      e.stopPropagation();
      const url = `${location.origin}${location.pathname}#/discover?faq=${itemId}`;
      const copyTextEl = copyBtn.querySelector('.stf-copy-text');
      const originalText = copyTextEl ? copyTextEl.textContent : '';

      try {
        if (navigator.clipboard && navigator.clipboard.writeText) {
          await navigator.clipboard.writeText(url);
        } else {
          const ta = document.createElement('textarea');
          ta.value = url;
          ta.style.position = 'fixed';
          ta.style.opacity = '0';
          document.body.appendChild(ta);
          ta.select();
          document.execCommand('copy');
          ta.remove();
        }

        if (copyTextEl) {
          copyTextEl.textContent = isAr ? 'تم نسخ الرابط!' : 'Link copied!';
          setTimeout(() => {
            copyTextEl.textContent = originalText;
          }, 1800);
        }
      } catch (err) {
        console.warn('Clipboard write error:', err);
      }
    });
  });

  // Handle URL query on initial load
  function checkHash() {
    const hash = location.hash || '';
    const queryStr = hash.includes('?') ? hash.split('?')[1] : (location.search ? location.search.slice(1) : '');
    const params = new URLSearchParams(queryStr);
    const faqId = params.get('faq') || (hash.startsWith('#faq-') ? hash.replace('#faq-', '') : '');
    if (!faqId) return;
    const targetItem = items.find(it => it.getAttribute('data-id') === faqId);
    if (targetItem) {
      toggleItem(faqId);
      setTimeout(() => {
        targetItem.scrollIntoView({ behavior: 'smooth', block: 'center' });
      }, 100);
    }
  }
  checkHash();
  window.addEventListener('hashchange', checkHash);

  // Initialize counts
  updateCountsAndVisibility();

  // Return cleanup function
  return () => {
    introObserver?.disconnect();
    clearTimeout(introTimeout);
    closingTimers.forEach(t => clearTimeout(t));
    tickerToggle?.removeEventListener('click', handleTickerToggle);
    searchInput?.removeEventListener('input', onSearchInput);
    clearBtn?.removeEventListener('click', clearSearch);
    resetBtn?.removeEventListener('click', resetFilters);
    window.removeEventListener('hashchange', checkHash);
  };
}

export default { renderSlitTypeFaq, mountSlitTypeFaq };
