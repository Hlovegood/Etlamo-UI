/**
 * Escapes HTML characters.
 */
function escapeHtml(str) {
  return String(str ?? '').replace(/[&<>"']/g, char => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;'
  }[char]));
}

/**
 * Splits query string into searchable words.
 */
function getQueryWords(query) {
  return query
    .toLowerCase()
    .trim()
    .split(/\s+/)
    .filter(w => w.length > 0);
}

/**
 * Highlights matches of query words in text.
 */
function highlightText(text, query) {
  const words = getQueryWords(query);
  if (!words.length) return escapeHtml(text);

  const escapedWords = words.map(w => w.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'));
  const regex = new RegExp(`(${escapedWords.join('|')})`, 'gi');
  const parts = text.split(regex);

  return parts
    .map(part => {
      if (words.some(w => w.toLowerCase() === part.toLowerCase())) {
        return `<mark class="stf-mark">${escapeHtml(part)}</mark>`;
      }
      return escapeHtml(part);
    })
    .join('');
}

